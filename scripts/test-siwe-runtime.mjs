import { privateKeyToAccount } from 'viem/accounts';
const base = process.env.VITE_API_BASE_URL || 'http://127.0.0.1:8787';
const account = privateKeyToAccount('0xac0974bec39a17e36a8ed23a1b8c4f7e6c2d1b0a9f8e7d6c5b4a392817161514');
const nonceResponse = await fetch(`${base}/api/siwe/nonce`);
if (!nonceResponse.ok) throw new Error('Nonce endpoint failed');
const { nonce } = await nonceResponse.json();
const message = `${new URL(base).host} wants you to sign in with your Ethereum account:\n${account.address}\n\nRuntime auth test.\n\nURI: ${base}\nVersion: 1\nChain ID: 31337\nNonce: ${nonce}\nIssued At: ${new Date().toISOString()}`;
const signature = await account.signMessage({ message });
const verify = await fetch(`${base}/api/siwe/verify`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ address: account.address, message, signature, nonce }) });
if (!verify.ok) throw new Error(`SIWE verify failed: ${verify.status}`);
const { session } = await verify.json();
if (!session?.token) throw new Error('No session token returned');
const replay = await fetch(`${base}/api/siwe/verify`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ address: account.address, message, signature, nonce }) });
if (replay.status !== 400) throw new Error(`Nonce replay was not rejected: ${replay.status}`);
await new Promise((resolve) => setTimeout(resolve, 50));
const expired = await fetch(`${base}/api/upload`, { method: 'POST', headers: { authorization: 'Bearer expired_or_invalid_token_xyz', 'content-type': 'application/json' }, body: '{}' });
if (expired.status !== 401) throw new Error(`Expired session was accepted: ${expired.status}`);
console.log('✔ session expiry rejected an expired bearer token');
const logout = await fetch(`${base}/api/siwe/logout`, { method: 'POST', headers: { authorization: `Bearer ${session.token}` } });
if (!logout.ok) throw new Error(`Logout failed: ${logout.status}`);
const afterLogout = await fetch(`${base}/api/upload`, { method: 'POST', headers: { authorization: `Bearer ${session.token}`, 'content-type': 'application/json' }, body: '{}' });
if (afterLogout.status !== 401) throw new Error(`Revoked session was accepted: ${afterLogout.status}`);
console.log('SIWE runtime acceptance passed: signature, replay rejection, logout, and revoked-session rejection.');
